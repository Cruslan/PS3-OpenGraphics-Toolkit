int main(int argc, char* argv[]) {
    char out_dir[MAX_PATH_LEN] = "shaders";

    for (int i = 1; i < argc; i++) {
        if (strcmp(argv[i], "--output-dir") == 0 && i + 1 < argc) {
            strncpy(out_dir, argv[++i], sizeof(out_dir) - 1);
        } else if (strcmp(argv[i], "--help") == 0) {
            printf("Usage: %s [--output-dir <directory>]\n", argv[0]);
            return 0;
        }
    }

    mkdir(out_dir, 0755);
    size_t count = sizeof(g_shaders) / sizeof(g_shaders[0]);

    for (size_t i = 0; i < count; i++) {
        char filepath[MAX_PATH_LEN];
        snprintf(filepath, sizeof(filepath), "%s/%s", out_dir, g_shaders[i].filename);
        FILE* fp = fopen(filepath, "w");
        if (!fp) {
            fprintf(stderr, "[ERROR] Failed to create %s\n", filepath);
            return 1;
        }
        fputs(g_shaders[i].content, fp);
        fclose(fp);
        printf("Generated %s\n", filepath);
    }

    printf("Total shaders generated: %zu\n", count);
    return 0;
}
